--- Resolves the DCS aircraft type for a flight based on its origin country.
-- Falls back to CONFIG.aircraft_type when the origin country is not mapped.
-- @param flight Flight record from parseFlight()
-- @return string DCS aircraft model name
local function resolveAircraftType(flight)
    local country = flight.origin_country
    if country and CONFIG.aircraft_types[country] then
        return CONFIG.aircraft_types[country]
    end
    return CONFIG.aircraft_type
end

--- Resolves the livery_id for a flight based on its origin country.
-- Falls back to the configured default livery when the origin country is not mapped.
-- @param flight Flight record from parseFlight()
-- @return string DCS livery id
local function resolveAircraftLivery(flight)
    local country = flight.origin_country
    if country and CONFIG.aircraft_liveries[country] then
        return CONFIG.aircraft_liveries[country]
    end
    return CONFIG.aircraft_liveries["default"] or "default"
end

--- Spawns a single civilian aircraft from a processed flight record.
-- Wrapped in pcall so a single invalid/out-of-map flight does not abort the whole feed pass.
-- @param flight Flight record from parseFlight()
-- @return boolean Success status of the spawn operation
local function spawnCIVAIRAsset(flight)
    local ok, err = pcall(function()
        -- Enforce the global spawn limit
        local currentCount = countActiveAssets("plane")
        if currentCount >= CONFIG.maximum_spawn_limit then
            debugMsg("Maximum spawn limit reached (" .. currentCount .. "/" .. CONFIG.maximum_spawn_limit .. "). Skipping " .. flight.callsign)
            return false
        end

        -- Convert geographic lat/lon to DCS local coordinates
        local point = coord.LLtoLO(flight.lat, flight.lon, flight.altitude)

        -- DCS world frame: x=north, z=east, y=up. Place a second waypoint far ahead along the
        -- feed heading so the aircraft actually flies that bearing (a single waypoint gives DCS
        -- no onward direction to follow).
        local hdgRad = math.rad(flight.headingDeg)
        local fwd = 50 * 1000 -- 50km ahead
        local wp2North = point.x + math.cos(hdgRad) * fwd
        local wp2East  = point.z + math.sin(hdgRad) * fwd

        -- Increment group counter and build names
        CIVAIR_STATE.groupCounter = CIVAIR_STATE.groupCounter + 1
        local groupName = flight.callsign
        local unitName = flight.callsign
        local groupId = math.random(1000, 9999)
        local unitId = math.random(10000, 99999)

        local groupData = {
            ["visible"] = false,
            ["tasks"] = {},
            ["uncontrollable"] = false,
            ["task"] = "Nothing",
            ["taskSelected"] = true,
            ["route"] = {
                ["points"] = {
                    [1] = {
                        ["alt"] = flight.altitude,
                        ["type"] = "Turning Point",
                        ["action"] = "Turning Point",
                        ["alt_type"] = "BARO",
                        ["speed"] = flight.speed,
                        ["y"] = point.z,
                        ["x"] = point.x,
                        ["speed_locked"] = true,
                    },
                    [2] = {
                        ["alt"] = flight.altitude,
                        ["type"] = "Turning Point",
                        ["action"] = "Turning Point",
                        ["alt_type"] = "BARO",
                        ["speed"] = flight.speed,
                        ["y"] = wp2East,
                        ["x"] = wp2North,
                        ["speed_locked"] = true,
                    },
                }
            },
            ["groupId"] = groupId,
            ["hidden"] = false,
            ["units"] = {},
            ["y"] = point.z,
            ["x"] = point.x,
            ["name"] = groupName,
            ["start_time"] = 0,
        }

        local unit = {
            ["type"] = resolveAircraftType(flight),
            ["unitId"] = unitId,
            ['callsign'] = {
                ["name"] = unitName,
                ["number"] = 15 + CIVAIR_STATE.groupCounter,
                ["modulation"] = 0,
                ["tone"] = 0
            },
            ["skill"] = "High",
            ["livery_id"] = resolveAircraftLivery(flight),
            ["onboard_num"] = string.format("%03d", 15 + CIVAIR_STATE.groupCounter),
            ["y"] = point.z,
            ["x"] = point.x,
            ["name"] = unitName,
            ["heading"] = math.rad(flight.headingDeg),
            ["speed"] = flight.speed,
            ["alt"] = flight.altitude,
            ["alt_type"] = "BARO",
            ["payload"] = {
                ["pylons"] = {},
                ["fuel"] = 60000,
                ["flare"] = 60,
                ["chaff"] = 120,
                ["gun"] = 100,
            }
        }

        groupData.units[1] = unit

        debugMsg("Spawning " .. resolveAircraftType(flight) .. " '" .. flight.callsign .. "' at LAT=" .. flight.lat .. ", LON=" .. flight.lon ..
                 " -> X=" .. math.floor(point.x) .. ", Z=" .. math.floor(point.z) .. ", alt=" .. math.floor(flight.altitude) ..
                 "m, hdg=" .. math.floor(flight.headingDeg) .. "°, spd=" .. math.floor(flight.speed) .. " m/s")

        local success, result = pcall(coalition.addGroup, CONFIG.country, Group.Category.AIRPLANE, groupData)

        if success and result then
            debugMsg("Spawned civilian aircraft: " .. groupName)
            CIVAIR_STATE.SPAWNED_PLANES[flight.callsign] = {
                group = result,
                unitName = unitName,
                spawnTime = timer.getTime(),
                icao24 = flight.icao24,
                lastFeedTimestamp = CIVAIR_STATE.feedTimestamp,
                feedLat = flight.lat,
                feedLon = flight.lon,
                feedAlt = flight.altitude,
                feedHeading = flight.headingDeg,
                feedSpeed = flight.speed,
            }
            return true
        else
            debugMsg("ERROR: Failed to spawn " .. flight.callsign .. ": " .. tostring(result))
            return false
        end
    end)

    if not ok then
        debugMsg("ERROR spawning " .. tostring(flight and flight.callsign) .. ": " .. tostring(err))
        return false
    end

    -- When pcall succeeds, its second result is the inner function's return value
    return err
end

--- Approximate horizontal distance (meters) between two lat/lon points.
-- Uses a simple equirectangular projection valid for the small feeds used here.
-- @param lat1, lon1 first point
-- @param lat2, lon2 second point
-- @return number Distance in meters
local function distanceMeters(lat1, lon1, lat2, lon2)
    local earthRadiusM = 6371000
    local dLat = math.rad(lat2 - lat1)
    local dLon = math.rad(lon2 - lon1)
    local x = dLon * math.cos(math.rad((lat1 + lat2) / 2))
    local y = dLat
    return math.sqrt(x * x + y * y) * earthRadiusM
end

--- Normalizes a heading difference to the [-180, 180] range.
-- @param a first heading in degrees
-- @param b second heading in degrees
-- @return number Signed smallest angular difference
local function headingDeltaDeg(a, b)
    local d = (a - b) % 360
    if d > 180 then d = d - 360 end
    return d
end

--- Re-tasks an already-spawned plane when its real-world position, heading or
-- altitude in the feed has deviated "wildly" from where DCS is currently flying it.
-- Rebuilds the route so the aircraft is repositioned and holds the feed altitude.
-- @param callsign the aircraft's callsign (also the group/unit name)
-- @param flight current flight record from the feed
-- @param assetData the spawned asset state entry
-- @return boolean true if an update was applied
local function updateCIVAIRAsset(callsign, flight, assetData)
    local unit = assetData.group and assetData.group:getUnit(1)
    if not unit or not unit:isExist() then
        return false
    end

    -- Current in-game position and heading of the unit
    local pos = unit:getPoint()
    if not pos then
        return false
    end
    local curLat, curLon = coord.LOtoLL(pos)
    if not curLat or not curLon then
        return false
    end
    local vel = unit:getVelocity()
    local curHdg = 0
    if vel and (math.abs(vel.x) > 0.01 or math.abs(vel.z) > 0.01) then
        -- DCS world frame: vel.x = north component, vel.z = east component.
        -- Compass heading (0=North, 90=East) = atan2(east, north) = atan2(vel.z, vel.x)
        curHdg = math.deg(math.atan2(vel.z, vel.x))
        if curHdg < 0 then curHdg = curHdg + 360 end
    end
    local curAlt = pos.y

    -- True comparison: where DCS is actually flying the plane vs where the feed says it should be.
    -- The plane legitimately moves ahead along its route between feed updates, so a generous
    -- position threshold absorbs normal forward progress; large deviations (off-track / descended)
    -- trigger a correction.
    local curDistFromFeed = distanceMeters(curLat, curLon, flight.lat, flight.lon)
    local curAltDelta = math.abs(curAlt - flight.altitude)
    local curHdgDelta = math.abs(headingDeltaDeg(curHdg, flight.headingDeg))

    local needsPos = curDistFromFeed > CONFIG.update_position_threshold_m
    local needsHdg = curHdgDelta > CONFIG.update_heading_threshold_deg
    local needsAlt = curAltDelta > CONFIG.update_altitude_threshold_m

    if not (needsPos or needsHdg or needsAlt) then
        -- Aircraft is on track and on altitude; just refresh the stored feed reference
        assetData.feedLat = flight.lat
        assetData.feedLon = flight.lon
        assetData.feedAlt = flight.altitude
        assetData.feedHeading = flight.headingDeg
        assetData.feedSpeed = flight.speed
        assetData.lastFeedTimestamp = CIVAIR_STATE.feedTimestamp
        return false
    end

    debugMsg("Updating " .. callsign ..
        " (pos " .. math.floor(curDistFromFeed) .. "m, hdg " .. math.floor(curHdgDelta) .. "deg, alt " .. math.floor(curAltDelta) ..
        "m) -> feed pos (lat " .. flight.lat .. ", lon " .. flight.lon .. ", alt " .. flight.altitude .. "m, hdg " .. flight.headingDeg .. ", spd " .. flight.speed .. ")")

    -- Rebuild a holding route at the new feed position, altitude, heading and speed
    local point = coord.LLtoLO(flight.lat, flight.lon, flight.altitude)

    -- Place the second waypoint far ahead along the feed heading so the plane cruises level.
    -- DCS world frame: x=north, z=east, so north offset = cos(heading), east offset = sin(heading).
    local hdgRad = math.rad(flight.headingDeg)
    local fwd = 50 * 1000 -- 50km ahead
    local x2 = point.x + math.cos(hdgRad) * fwd
    local z2 = point.z + math.sin(hdgRad) * fwd

    local newRoute = {
        ["points"] = {
            [1] = {
                ["alt"] = flight.altitude,
                ["type"] = "Turning Point",
                ["action"] = "Turning Point",
                ["alt_type"] = "BARO",
                ["speed"] = flight.speed,
                ["speed_locked"] = true,
                ["y"] = point.z,
                ["x"] = point.x,
            },
            [2] = {
                ["alt"] = flight.altitude,
                ["type"] = "Turning Point",
                ["action"] = "Turning Point",
                ["alt_type"] = "BARO",
                ["speed"] = flight.speed,
                ["speed_locked"] = true,
                ["y"] = z2,
                ["x"] = x2,
            },
        }
    }

    local ok, err2 = pcall(function()
        assetData.group:getController():setTask(
            { id = 'Mission', params = { route = newRoute } }
        )
    end)
    if not ok then
        debugMsg("ERROR updating task for " .. callsign .. ": " .. tostring(err2))
        return false
    end

    -- Refresh stored feed reference values
    assetData.feedLat = flight.lat
    assetData.feedLon = flight.lon
    assetData.feedAlt = flight.altitude
    assetData.feedHeading = flight.headingDeg
    assetData.feedSpeed = flight.speed
    assetData.lastFeedTimestamp = CIVAIR_STATE.feedTimestamp
    return true
end

