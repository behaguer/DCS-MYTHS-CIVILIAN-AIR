--- Removes spawned aircraft that are no longer present in the feed or no longer exist.
-- This prevents clutter from aircraft whose real-world flight has ended.
-- @param feed Map of callsign -> flight record from the current feed
-- @param fresh If false, force removal based on spawn age (garbage collection)
-- @return void
local function garbageCollectPlanes(feed, fresh)
    local now = timer.getTime()

    for callsign, assetData in pairs(CIVAIR_STATE.SPAWNED_PLANES) do
        local remove = false

        -- Removed if the group no longer exists (shot down / despawned)
        if not (assetData.group and assetData.group:isExist()) then
            remove = true
            debugMsg("GC: Removing " .. callsign .. " (group no longer exists)")
        -- Removed if its flight is no longer in the feed (flight ended / left the map)
        elseif not feed[callsign] then
            remove = true
            debugMsg("GC: Removing " .. callsign .. " (no longer in feed)")
        end

        if remove then
            if assetData.group and assetData.group:isExist() then
                assetData.group:destroy()
            end
            CIVAIR_STATE.SPAWNED_PLANES[callsign] = nil
        end
    end
end

--- Main feed processing cycle: reads the file, spawns missing aircraft, and cleans up.
-- @return void
local function processFeed()
    if not CONFIG.enable_api then
        return
    end

    -- TODO #1: Read the data from the file based off the time set in configuration
    local feed = readFeed()
    debugMsg("Feed check complete. " .. countTableKeys(feed) .. " flights, " .. countActiveAssets("plane") .. " already spawned.")

    -- TODO #2: Spawn the aircraft that are missing from the state but present in the file
    for callsign, flight in pairs(feed) do
        local assetData = CIVAIR_STATE.SPAWNED_PLANES[callsign]
        if not assetData then
            debugMsg("Spawning missing aircraft: " .. callsign)
            spawnCIVAIRAsset(flight)
        elseif assetData.group and assetData.group:isExist() then
            -- Already spawned: check for position/direction/altitude drift and correct it
            updateCIVAIRAsset(callsign, flight, assetData)
        end
    end

    -- TODO #3: Garbage collection - remove aircraft no longer in the feed
    garbageCollectPlanes(feed)

    -- Re-schedule the next feed check so the monitor loop keeps running
    timer.scheduleFunction(processFeed, nil, timer.getTime() + CONFIG.api_feed_monitor_frequency)
end

--- Initializes the CIVAIR system.
-- @return void
local function initializeCIVAIR()
    if CIVAIR_STATE.initialized then
        return
    end

    debugMsg("Initializing CIVAILIAN AIR system...")
    CIVAIR_STATE.initialized = true

    -- Abort early if DCS file-system access is not enabled (required to read the feed)
    if not isFileSystemEnabled() then
        return
    end

    debugMsg("CIVILAN AIR system initialized successfully!")

    -- processFeed() re-schedules itself, so the monitor loop continues indefinitely
    processFeed()
end

-- Initialize the system
initializeCIVAIR()