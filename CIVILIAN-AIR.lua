--- Verifies that DCS file-system access is enabled so the feed file can be read.
-- DCS must be started with the "fs" sandbox flag (io/lfs available).
-- @return boolean True if file-system access is available
local function isFileSystemEnabled()
    if io and type(io.open) == "function" then
        return true
    end
    debugMsg("ERROR: DCS file-system (fs) access is not enabled. Add the 'fs' sandbox flag so the feed file can be read.", true)
    return false
end

--- Reads the entire contents of a file from outside the mission.
-- Tries the path as-is first (absolute paths work best), then common DCS base
-- directories for relative paths, since DCS's working directory may not be
-- the folder where the feed file lives.
-- @param path Relative or absolute path to the file
-- @return string|nil File contents as a string, or nil if it could not be read
local function readExternalFile(path)
    if not isFileSystemEnabled() then
        return nil
    end

    local f = io.open(path, "r")
    if f then
        local contents = f:read("*all")
        f:close()
        return contents
    end

    debugMsg("ERROR: Could not open feed file: " .. tostring(path))
    return nil
end


-- =====================================================================================
-- JSON PARSER (recursive descent - no loadstring required)
-- =====================================================================================

local jsonPos, jsonSrc

local function jsonPeek()
    while jsonPos <= #jsonSrc do
        local c = jsonSrc:byte(jsonPos)
        if c == 32 or c == 9 or c == 10 or c == 13 then
            jsonPos = jsonPos + 1
        else
            break
        end
    end
    if jsonPos > #jsonSrc then return nil end
    return string.char(jsonSrc:byte(jsonPos))
end

local function jsonAdvance()
    jsonPos = jsonPos + 1
end

local function jsonReadString()
    jsonAdvance() -- skip opening "
    local start = jsonPos
    local parts = {}
    while jsonPos <= #jsonSrc do
        local c = jsonSrc:byte(jsonPos)
        if c == 34 then -- "
            if jsonPos > start then
                parts[#parts + 1] = jsonSrc:sub(start, jsonPos - 1)
            end
            jsonAdvance()
            return table.concat(parts)
        elseif c == 92 then -- backslash
            if jsonPos > start then
                parts[#parts + 1] = jsonSrc:sub(start, jsonPos - 1)
            end
            jsonAdvance()
            local e = string.char(jsonSrc:byte(jsonPos))
            if e == "n" then parts[#parts + 1] = "\n"
            elseif e == "r" then parts[#parts + 1] = "\r"
            elseif e == "t" then parts[#parts + 1] = "\t"
            elseif e == "b" then parts[#parts + 1] = "\b"
            elseif e == "f" then parts[#parts + 1] = "\f"
            else parts[#parts + 1] = e end
            jsonAdvance()
            start = jsonPos
        else
            jsonPos = jsonPos + 1
        end
    end
    return table.concat(parts)
end

local function jsonReadNumber()
    local start = jsonPos
    if jsonSrc:byte(jsonPos) == 45 then jsonPos = jsonPos + 1 end -- minus
    while jsonPos <= #jsonSrc and jsonSrc:byte(jsonPos) >= 48 and jsonSrc:byte(jsonPos) <= 57 do
        jsonPos = jsonPos + 1
    end
    if jsonPos <= #jsonSrc and jsonSrc:byte(jsonPos) == 46 then -- dot
        jsonPos = jsonPos + 1
        while jsonPos <= #jsonSrc and jsonSrc:byte(jsonPos) >= 48 and jsonSrc:byte(jsonPos) <= 57 do
            jsonPos = jsonPos + 1
        end
    end
    if jsonPos <= #jsonSrc and (jsonSrc:byte(jsonPos) == 101 or jsonSrc:byte(jsonPos) == 69) then -- e/E
        jsonPos = jsonPos + 1
        if jsonPos <= #jsonSrc and (jsonSrc:byte(jsonPos) == 43 or jsonSrc:byte(jsonPos) == 45) then -- +/-
            jsonPos = jsonPos + 1
        end
        while jsonPos <= #jsonSrc and jsonSrc:byte(jsonPos) >= 48 and jsonSrc:byte(jsonPos) <= 57 do
            jsonPos = jsonPos + 1
        end
    end
    return tonumber(jsonSrc:sub(start, jsonPos - 1))
end

local function jsonReadValue()
    local c = jsonPeek()
    if c == '"' then
        return jsonReadString()
    elseif c == '{' then
        jsonAdvance() -- skip {
        local obj = {}
        jsonPeek()
        if jsonSrc:byte(jsonPos) == 125 then -- }
            jsonAdvance()
            return obj
        end
        while true do
            jsonPeek()
            local key = jsonReadString()
            jsonPeek() jsonAdvance() -- skip :
            local val = jsonReadValue()
            obj[key] = val
            jsonPeek()
            if jsonSrc:byte(jsonPos) == 44 then -- ,
                jsonAdvance()
            else
                break
            end
        end
        jsonPeek() jsonAdvance() -- skip }
        return obj
    elseif c == '[' then
        jsonAdvance() -- skip [
        local arr = {}
        jsonPeek()
        if jsonSrc:byte(jsonPos) == 93 then -- ]
            jsonAdvance()
            return arr
        end
        while true do
            arr[#arr + 1] = jsonReadValue()
            jsonPeek()
            if jsonSrc:byte(jsonPos) == 44 then -- ,
                jsonAdvance()
            else
                break
            end
        end
        jsonPeek() jsonAdvance() -- skip ]
        return arr
    elseif c == 't' then
        jsonPos = jsonPos + 4
        return true
    elseif c == 'f' then
        jsonPos = jsonPos + 5
        return false
    elseif c == 'n' then
        jsonPos = jsonPos + 4
        return nil
    else
        return jsonReadNumber()
    end
end

local function jsonDecode(s)
    if not s or #s == 0 then
        debugMsg("ERROR: jsonDecode received empty input")
        return nil
    end
    jsonSrc = s
    jsonPos = 1
    local ok, result = pcall(jsonReadValue)
    if not ok then
        debugMsg("JSON parse error: " .. tostring(result))
        return nil
    end
    return result
end

--- Normalizes a callsign from the feed (strips leading/trailing whitespace).
-- @param rawCallsign Raw callsign string from the feed
-- @return string Normalized callsign, or nil if empty
local function normalizeCallsign(rawCallsign)
    if not rawCallsign then
        return nil
    end
    local callsign = rawCallsign:gsub("^%s+", ""):gsub("%s+$", "")
    if callsign == "" then
        return nil
    end
    return callsign
end

--- Converts one OpenSky state vector into a flight record usable by DCS.
-- Skips states that are on the ground, filtered out, or have no usable coordinates.
-- @param state The raw state vector array
-- @return table|nil Flight record, or nil if the state should be ignored
local function parseFlight(state)
    if type(state) ~= "table" then
        return nil
    end

    local callsign = normalizeCallsign(state[SV_CALLSIGN])
    local lat = state[SV_LATITUDE]
    local lon = state[SV_LONGITUDE]

    -- Skip flights with no callsign/coords
    if not callsign or callsign == "" or lat == nil or lon == nil then
        return nil
    end

    -- Skip flights on the ground
    if state[SV_ON_GROUND] then
        return nil
    end

    -- Altitude: prefer barometric altitude, fall back to geometric
    local altitude = state[SV_BARO_ALTITUDE] or state[SV_GEO_ALTITUDE] or 0

    -- Skip flights below the configured minimum altitude
    if altitude < CONFIG.min_altitude then
        return nil
    end

    -- Apply the ignore callsign list
    for _, ignored in ipairs(CONFIG.ignore_callsigns) do
        if callsign == ignored then
            return nil
        end
    end

    -- Velocity: fall back to the configured default cruise speed
    local speed = state[SV_VELOCITY] or CONFIG.default_cruise_speed

    -- Heading in degrees (true track from the feed)
    local headingDeg = state[SV_TRUE_TRACK] or 0

    -- Ensure altitude respects a minimum so aircraft never spawn underground
    altitude = math.max(altitude, CONFIG.min_altitude)

    return {
        icao24 = state[SV_ICAO24],
        callsign = callsign,
        origin_country = state[SV_ORIGIN_COUNTRY],
        lat = lat,
        lon = lon,
        altitude = altitude,
        speed = speed,
        headingDeg = headingDeg,
    }
end

--- Counts keys in a table.
-- @param t The table
-- @return number Number of keys
local function countTableKeys(t)
    local n = 0
    for _ in pairs(t) do
        n = n + 1
    end
    return n
end

--- Reads, parses and caches the feed file.
-- Returns a map of callsign -> flight record for all currently valid flights.
-- @return table Map of callsign -> flight record
local function readFeed()
    local flights = {}

    if not CONFIG.enable_api then
        return flights
    end

    local json = readExternalFile(CONFIG.api_feed_path)
    if not json then
        return flights
    end

    local data = jsonDecode(json)
    if type(data) ~= "table" then
        debugMsg("ERROR: Failed to parse feed file: " .. CONFIG.api_feed_path)
        return flights
    end

    -- Record when the feed data was generated (OpenSky timestamp)
    CIVAIR_STATE.feedTimestamp = data.timestamp

    local states = data.states
    if not states then
        debugMsg("ERROR: Feed file has no 'states' field")
        return flights
    end

    local parsed = 0
    for _, state in ipairs(states) do
        local flight = parseFlight(state)
        if flight then
            flights[flight.callsign] = flight
            parsed = parsed + 1
        end
    end

    debugMsg("Parsed " .. parsed .. " airborne flights from feed (call sign map size: " .. (countTableKeys(flights)) .. ")")
    return flights
end

